// Preserve Bazaar declarations; prefix every selector to isolate the storefront.
// Uses PostCSS already installed as a Vite dependency. Not run during builds.
import postcss from 'postcss';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const source = new URL('../../docs/bazaar_template/css/style.css', import.meta.url);
const destination = new URL('../src/styles/bazaar.scoped.css', import.meta.url);
const root = postcss.parse(await readFile(source, 'utf8'));
root.walkRules((rule) => {
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
  }
  rule.selectors = rule.selectors.map((selector) => {
    if ([':root', 'body', 'html'].includes(selector)) return '.storefront';
    return `.storefront ${selector}`;
  });
});
await mkdir(new URL('../src/styles/', import.meta.url), { recursive: true });
await writeFile(destination, '/* Generated by scripts/prepare-bazaar-css.mjs. Original Bazaar CSS: uiCookies. */\n' + root.toString());
console.log('Prepared scoped Bazaar CSS; original file unchanged.');
